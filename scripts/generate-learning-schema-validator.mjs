import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import Ajv2020 from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const schemaPath = path.join(
  root,
  'src',
  'learning',
  'content',
  'schemas',
  'learning-pack-v1.schema.json',
)
const outputPath = path.join(
  root,
  'src',
  'learning',
  'content',
  'schemas',
  'learning-pack-v1.validator.js',
)
const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'))
const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  code: { source: true, esm: true, lines: true },
})
const validate = ajv.compile(schema)
const generated = standaloneCode(ajv, validate)
const cspSafeGenerated = generated.replace(
  /const (func\d+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/,
  `const $1 = (value) => {
  let length = 0;
  let position = 0;
  while (position < value.length) {
    length += 1;
    const code = value.charCodeAt(position++);
    if (code >= 0xd800 && code <= 0xdbff && position < value.length) {
      const next = value.charCodeAt(position);
      if ((next & 0xfc00) === 0xdc00) position += 1;
    }
  }
  return length;
};`,
)
if (/\brequire\s*\(/.test(cspSafeGenerated) || /\b(?:eval|Function)\s*\(/.test(cspSafeGenerated)) {
  throw new Error('The generated validator is not self-contained or CSP-safe.')
}
const banner = [
  '/* Generated by scripts/generate-learning-schema-validator.mjs. Do not edit manually. */',
  '',
].join('\n')

fs.writeFileSync(outputPath, `${banner}${cspSafeGenerated}`, 'utf8')
console.log(`Generated CSP-safe learning schema validator: ${path.relative(root, outputPath)}`)
